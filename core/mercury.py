def _utc(iso: str) -> datetime:
    return datetime.fromisoformat(iso).replace(tzinfo=timezone.utc)


_INTERVALS: tuple[tuple[datetime, datetime], ...] = tuple(
    (_utc(begin), _utc(end)) for begin, end in _RETRO_INTERVALS)

TABLE_SINCE = _utc(_TABLE_FROM)
# Дальше конца последнего интервала таблица не знает, будет ли следующая
# ретрограда, поэтому это и есть граница её применимости.
TABLE_UNTIL = _INTERVALS[-1][1]


@dataclass
class MercuryInfo:
    retrograde: bool
    begin: datetime      # начало текущей ретрограды (или следующей, если сейчас прямое)
    end: datetime        # её же конец
    now: datetime        # момент, на который посчитано


def get_mercury_info(when: datetime | None = None, *,
                     tz_offset: float = OMSK_TZ_OFFSET) -> MercuryInfo:
    """Состояние Меркурия на момент `when` (по умолчанию — сейчас).

    Моменты в результате приведены к часовому поясу tz_offset.
    Бросает LookupError, если момент вне периода, покрытого таблицей.
    """
    now = when or datetime.now(timezone.utc)
    if now.tzinfo is None:
        now = now.replace(tzinfo=timezone.utc)
    now = now.astimezone(timezone.utc)

    if not TABLE_SINCE <= now <= TABLE_UNTIL:
        raise LookupError(
            f"таблица покрывает {TABLE_SINCE:%Y}-{TABLE_UNTIL:%Y}, "
            f"запрошен {now:%Y-%m-%d}")

    tz = timezone(timedelta(hours=tz_offset))
    for begin, end in _INTERVALS:
        if now > end:
            continue
        # Первый интервал, не оставшийся в прошлом: либо мы внутри него,
        # либо он ещё впереди.
        return MercuryInfo(retrograde=begin <= now, begin=begin.astimezone(tz),
                           end=end.astimezone(tz), now=now.astimezone(tz))
    raise AssertionError("недостижимо: момент внутри таблицы, но интервал не найден")


def is_retrograde(when: datetime | None = None) -> bool:
    """Короткий ответ «да/нет» — для использования из другого кода."""
    return get_mercury_info(when).retrograde


def _human_delta(delta: timedelta) -> str:
    """Длительность словами, с точностью, уместной для показанного масштаба."""
    total = max(int(delta.total_seconds()), 0)
    days, rest = divmod(total, 86400)
    hours, rest = divmod(rest, 3600)
    if days >= 2:
        return f"{days} дн"
    if days:
        return f"{days} дн {hours} ч"
    if hours:
        return f"{hours} ч"
    return f"{max(rest // 60, 1)} мин"


def format_mercury(info: MercuryInfo) -> str:
    span = f"{info.begin:%d.%m %H:%M} - {info.end:%d.%m %H:%M}"
    if info.retrograde:
        return "\n".join((
            f"{MERCURY} Меркурий ретрограден",
            span,
            f"осталось {_human_delta(info.end - info.now)}",
        ))
    return "\n".join((
        f"{MERCURY} Меркурий прямой",
        f"ретро {span}",
        f"через {_human_delta(info.begin - info.now)}",
    ))


async def get_mercury(tz_offset: float = OMSK_TZ_OFFSET) -> str:
    """Готовый текст для команды /mercury.

    Корутина ради единообразия с остальными источниками данных — сети здесь
    нет, вся работа сводится к поиску по таблице из 47 записей.
    """
    try:
        return format_mercury(get_mercury_info(tz_offset=tz_offset))
    except LookupError as e:
        return (f"❌ Данные о ретрограде кончились ({e}). "
                f"Обновить: scripts/gen_mercury_table.py")
